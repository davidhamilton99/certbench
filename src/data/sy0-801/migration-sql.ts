import type { Sy0801Map } from "./types";

/** A question written for SY0-801, in the shape both new-question sets use (src/data/sy0-801/new-questions). */
export interface V8NewQuestion {
  key: string;
  objective: string;
  difficulty: 1 | 2 | 3;
  question: string;
  options: readonly [string, string, string, string];
  answer: 0 | 1 | 2 | 3;
  explanation: string;
}

export interface Sy0801MigrationInput {
  map: Sy0801Map;
  /** The SY0-701 bank the map was decided from: [id, SY0-701 objective] rows (sy0-701-bank.json). */
  bank: readonly (readonly [string, string])[];
  /** SY0-701 id → [the copy's id, its SY0-801 objective], for every question copied (copies.json). */
  copies: Readonly<Record<string, readonly [string, string]>>;
  newQuestions: readonly V8NewQuestion[];
}

/** Every slug path_progress may hold once SY0-801 exists. */
export const PATH_PROGRESS_SLUGS = [
  "security-plus-sy0-701",
  "security-plus-sy0-801",
  "network-plus-n10-009",
  "a-plus-core1-220-1201",
  "a-plus-core2-220-1202",
] as const;

const str = (s: string) => `'${s.replace(/'/g, "''")}'`;
const optionsJson = (options: readonly string[], answer: number) =>
  str(JSON.stringify(options.map((text, i) => ({ text, is_correct: i === answer }))));
const rows = (list: string[]) => list.map((r) => `  ${r}`).join(",\n");

/** Active SY0-801 questions per objective once the migration has run: the copies plus the new questions. */
export function expectedCounts({ map, copies, newQuestions }: Sy0801MigrationInput): Record<string, number> {
  const out: Record<string, number> = Object.fromEntries(
    map.domains.flatMap((d) => d.objectives.map((o) => [o.code, 0]))
  );
  for (const [, code] of Object.values(copies)) out[code]++;
  for (const q of newQuestions) out[q.objective]++;
  return out;
}

/**
 * The SQL that adds Security+ SY0-801 as its own exam beside SY0-701, in one
 * transaction. Generated from src/data/sy0-801 by scripts/sy0-801/build-migration.ts.
 */
export function buildSy0801Migration(input: Sy0801MigrationInput): string {
  const { map, bank, copies, newQuestions } = input;
  const target = str(map.slug);
  const source = str(map.sourceSlug);
  const counts = expectedCounts(input);
  const total = Object.values(counts).reduce((s, n) => s + n, 0);
  const copyRows = Object.entries(copies).sort(([a], [b]) => a.localeCompare(b));

  for (const id of Object.keys(map.fixes)) {
    if (!copies[id]) throw new Error(`${id}: a fix for a question that isn't copied`);
  }

  const out: string[] = [];
  out.push(`-- Add Security+ ${map.examCode} as its own exam beside ${map.sourceExamCode}.
-- Generated by scripts/sy0-801/build-migration.ts from src/data/sy0-801:
-- edit those and regenerate; don't edit this file.
--
-- It only adds rows. ${map.sourceExamCode} keeps its exam, questions, enrollments and
-- saved paths exactly as they are. ${map.examCode} gets a copy of each ${map.sourceExamCode}
-- question that carries over, tagged to its ${map.examCode} objective and under the id
-- src/data/sy0-801/copies.json gives it, with ${map.examCode} wording where
-- src/data/sy0-801/map.ts gives one, plus its own new questions.`);

  out.push(`begin;`);

  out.push(`-- Stop before changing anything unless the database is the one this was built from.
do $$
declare
  src uuid := (select id from certifications where slug = ${source});
begin
  if src is null then
    raise exception '${map.sourceExamCode} is missing';
  end if;
  if exists (select 1 from certifications where slug = ${target}) then
    raise exception '${map.examCode} already exists: this migration has already run';
  end if;
  if (select count(*) from cert_questions where certification_id = src and is_active) <> ${bank.length} then
    raise exception '${map.sourceExamCode}: expected the ${bank.length}-question bank this migration was built from';
  end if;
end $$;`);

  out.push(`-- The exam: the same format and passing score as ${map.sourceExamCode}.
insert into certifications (slug, name, exam_code, vendor, total_exam_questions, passing_score, max_score, exam_duration_minutes)
values (${target}, 'CompTIA Security+', ${str(map.examCode)}, 'CompTIA', 90, ${map.passingScore}, 900, 90);`);

  out.push(`-- Domains, weighted as CompTIA's ${map.examCode} exam objectives weight them.
insert into cert_domains (certification_id, domain_number, title, exam_weight, sort_order)
select c.id, v.domain_number, v.title, v.weight, v.sort_order
from (values
${rows(map.domains.map((d, i) => `(${str(d.number)}, ${str(d.title)}, ${d.weight}, ${i + 1})`))}
) as v(domain_number, title, weight, sort_order)
join certifications c on c.slug = ${target};`);

  out.push(`-- Objectives, described in our own words: CompTIA's wording is copyrighted.
insert into cert_sub_objectives (domain_id, code, title, sort_order)
select d.id, v.code, v.title, v.sort_order
from (values
${rows(
  map.domains.flatMap((d) => d.objectives.map((o, i) => `(${str(d.number)}, ${str(o.code)}, ${str(o.title)}, ${i + 1})`))
)}
) as v(domain_number, code, title, sort_order)
join certifications c on c.slug = ${target}
join cert_domains d on d.certification_id = c.id and d.domain_number = v.domain_number;`);

  out.push(`-- A copy of each ${map.sourceExamCode} question that carries over, under its fixed id.
insert into cert_questions (id, certification_id, domain_id, sub_objective_id, question_text, options, correct_index, explanation, difficulty, is_active, is_diagnostic_eligible)
select v.copy_id::uuid, c.id, s.domain_id, s.id, q.question_text, q.options, q.correct_index, q.explanation, q.difficulty, true, q.is_diagnostic_eligible
from (values
${rows(copyRows.map(([sourceId, [copyId, code]]) => `(${str(sourceId)}, ${str(copyId)}, ${str(code)})`))}
) as v(source_id, copy_id, code)
join cert_questions q on q.id = v.source_id::uuid and q.is_active
join certifications c on c.slug = ${target}
join cert_domains d on d.certification_id = c.id
join cert_sub_objectives s on s.domain_id = d.id and s.code = v.code;`);

  for (const [sourceId, fix] of Object.entries(map.fixes)) {
    const set: string[] = [];
    if (fix.question) set.push(`question_text = ${str(fix.question)}`);
    if (fix.options) {
      if (fix.answer === undefined) throw new Error(`${sourceId}: new options need their answer`);
      set.push(`options = ${optionsJson(fix.options, fix.answer)}::jsonb`, `correct_index = ${fix.answer}`);
    } else if (fix.answer !== undefined) {
      throw new Error(`${sourceId}: a new answer needs the options it points into`);
    }
    set.push(`explanation = ${str(fix.explanation)}`, `updated_at = now()`);
    out.push(`-- ${map.examCode} wording for the copy of ${sourceId}: ${fix.why}
update cert_questions set
  ${set.join(",\n  ")}
where id = ${str(copies[sourceId][0])};`);
  }

  out.push(`-- New questions for what ${map.examCode} added (src/data/sy0-801/new-questions).
insert into cert_questions (certification_id, domain_id, sub_objective_id, question_text, options, correct_index, explanation, difficulty, is_active, is_diagnostic_eligible)
select c.id, s.domain_id, s.id, v.question_text, v.options::jsonb, v.correct_index, v.explanation, v.difficulty, true, true
from (values
${rows(
  newQuestions.map(
    (q) =>
      `(${str(q.objective)}, ${str(q.question)}, ${optionsJson(q.options, q.answer)}, ${q.answer}, ${str(q.explanation)}, ${q.difficulty})`
  )
)}
) as v(code, question_text, options, correct_index, explanation, difficulty)
join certifications c on c.slug = ${target}
join cert_domains d on d.certification_id = c.id
join cert_sub_objectives s on s.domain_id = d.id and s.code = v.code;`);

  out.push(`-- Saved paths may now belong to ${map.examCode} too.
alter table path_progress drop constraint if exists path_progress_cert_slug_check;
alter table path_progress add constraint path_progress_cert_slug_check check (cert_slug in (
  ${PATH_PROGRESS_SLUGS.map(str).join(", ")}
));`);

  out.push(`-- Check the result before committing: every question in place, on its objective.
do $$
declare
  dst uuid := (select id from certifications where slug = ${target});
  src uuid := (select id from certifications where slug = ${source});
begin
  if (select count(*) from cert_questions where certification_id = dst and is_active) <> ${total} then
    raise exception '${map.examCode}: expected ${total} active questions';
  end if;
  if exists (select 1 from cert_questions where certification_id = dst and sub_objective_id is null) then
    raise exception '${map.examCode}: a question has no objective';
  end if;
  if exists (
    select 1
    from (values
${rows(Object.entries(counts).map(([code, n]) => `  (${str(code)}, ${n})`))}
    ) as e(code, n)
    where e.n <> (
      select count(*)
      from cert_questions q
      join cert_sub_objectives s on s.id = q.sub_objective_id
      join cert_domains d on d.id = s.domain_id
      where d.certification_id = dst and s.code = e.code and q.is_active
    )
  ) then
    raise exception '${map.examCode}: an objective has the wrong number of questions';
  end if;
  if (select count(*) from cert_questions where certification_id = src and is_active) <> ${bank.length} then
    raise exception '${map.sourceExamCode}: its questions changed';
  end if;
end $$;`);

  out.push(`commit;`, ``);
  return out.join("\n\n");
}
