import type { N10009LiveFix, N10009NewQuestion } from "./types";

/** The migration's file name in supabase/migrations. */
export const N10_009_MIGRATION_FILE = "039_network_plus_n10_009_questions.sql";

export interface N10009MigrationInput {
  slug: string;
  examCode: string;
  /** Active questions per topic in the live bank the new questions were written against. */
  before: Readonly<Record<string, number>>;
  newQuestions: readonly N10009NewQuestion[];
  /** Corrections to live questions, each applied only while the live question still reads as it did. */
  liveFixes?: readonly N10009LiveFix[];
}

const str = (s: string) => `'${s.replace(/'/g, "''")}'`;
const optionsJson = (options: readonly string[], answer: number) =>
  str(JSON.stringify(options.map((text, i) => ({ text, is_correct: i === answer }))));
const rows = (list: string[]) => list.map((r) => `  ${r}`).join(",\n");

/** Active questions per topic once the migration has run: the live bank plus the new questions. */
export function expectedCounts({ before, newQuestions }: N10009MigrationInput): Record<string, number> {
  const out: Record<string, number> = { ...before };
  for (const q of newQuestions) {
    if (out[q.topic] === undefined) throw new Error(`${q.key}: topic ${q.topic} is not in the bank`);
    out[q.topic]++;
  }
  return out;
}

/** The SQL that checks one topic's count: it raises `message` when any topic differs from `counts`. */
function topicCheck(target: string, counts: Readonly<Record<string, number>>, message: string): string {
  return `  if exists (
    select 1
    from (values
${rows(Object.entries(counts).map(([code, n]) => `    (${str(code)}, ${n})`))}
    ) as e(code, n)
    where e.n <> (
      select count(*)
      from cert_questions q
      join cert_sub_objectives s on s.id = q.sub_objective_id
      join cert_domains d on d.id = s.domain_id
      join certifications c on c.id = d.certification_id
      where c.slug = ${target} and s.code = e.code and q.is_active
    )
  ) then
    raise exception ${str(message)};
  end if;`;
}

/**
 * The SQL that adds the new Network+ questions to the live bank, in one
 * transaction. Generated from src/data/n10-009 by scripts/n10-009/build-migration.ts.
 */
export function buildN10009Migration(input: N10009MigrationInput): string {
  const { slug, examCode, before, newQuestions, liveFixes = [] } = input;
  const target = str(slug);
  const total = Object.values(before).reduce((s, n) => s + n, 0);
  const counts = expectedCounts(input);
  const after = Object.values(counts).reduce((s, n) => s + n, 0);
  for (const f of liveFixes) {
    if (f.options && f.answer === undefined) throw new Error(`${f.id}: new options need their answer`);
    if (!f.options && f.answer !== undefined) throw new Error(`${f.id}: a new answer needs the options it points into`);
    // These texts are quoted inside the checks' dollar-quoted blocks, which "$$" would end early.
    for (const text of [f.was.question, f.was.explanation, f.question ?? "", f.explanation]) {
      if (text.includes("$$")) throw new Error(`${f.id}: a text contains "$$"`);
    }
  }

  const out: string[] = [];
  out.push(`-- Add ${newQuestions.length} new questions to Network+ ${examCode}, which takes its bank from
-- ${total} to ${after} active questions${liveFixes.length ? `, and correct ${liveFixes.length} live questions that were wrong` : ""}.
-- Generated by scripts/n10-009/build-migration.ts from src/data/n10-009:
-- edit those files and regenerate; do not edit this file.
--
-- It adds rows${liveFixes.length ? " and corrects the live questions named below" : ""}; every other live question, every
-- enrollment and every saved study path stays as it is. It stops before changing
-- anything unless the bank is the one the new questions were written against
-- (${total} active questions, with the per-topic counts below${liveFixes.length ? ", and each question to be\n-- corrected still reading exactly as it did" : ""}), and it checks the result before
-- it commits. Run it once.`);

  out.push(`begin;`);

  out.push(`-- Stop unless the bank is the one these questions were written against.
do $$
declare
  exam uuid := (select id from certifications where slug = ${target});
begin
  if exam is null then
    raise exception '${examCode} is missing';
  end if;
  if (select count(*) from cert_questions where certification_id = exam and is_active) <> ${total} then
    raise exception '${examCode}: expected the ${total}-question bank these questions were written against (has this migration already run?)';
  end if;
${topicCheck(target, before, `${examCode}: a topic does not hold the number of questions these were written against`)}
${liveFixes
  .map(
    (f) => `  if not exists (
    select 1 from cert_questions
    where id = ${str(f.id)} and certification_id = exam and is_active
      and question_text = ${str(f.was.question)}
      and explanation = ${str(f.was.explanation)}
  ) then
    raise exception ${str(`${examCode}: live question ${f.id} has changed since its correction was written`)};
  end if;`
  )
  .join("\n")}
end $$;`);

  for (const f of liveFixes) {
    const set: string[] = [];
    if (f.question) set.push(`question_text = ${str(f.question)}`);
    if (f.options) set.push(`options = ${optionsJson(f.options, f.answer as number)}::jsonb`, `correct_index = ${f.answer}`);
    set.push(`explanation = ${str(f.explanation)}`, `updated_at = now()`);
    out.push(`-- Correct live question ${f.id} (topic ${f.topic}): ${f.why}
update cert_questions set
  ${set.join(",\n  ")}
where id = ${str(f.id)};`);
  }

  out.push(`-- The new questions, each on its topic (src/data/n10-009/new-questions).
insert into cert_questions (certification_id, domain_id, sub_objective_id, question_text, options, correct_index, explanation, difficulty, is_active, is_diagnostic_eligible)
select c.id, s.domain_id, s.id, v.question_text, v.options::jsonb, v.correct_index, v.explanation, v.difficulty, true, true
from (values
${rows(
  newQuestions.map(
    (q) =>
      `(${str(q.topic)}, ${str(q.question)}, ${optionsJson(q.options, q.answer)}, ${q.answer}, ${str(q.explanation)}, ${q.difficulty})`
  )
)}
) as v(code, question_text, options, correct_index, explanation, difficulty)
join certifications c on c.slug = ${target}
join cert_domains d on d.certification_id = c.id
join cert_sub_objectives s on s.domain_id = d.id and s.code = v.code;`);

  out.push(`-- Check the result before committing: every question in place, on its topic.
do $$
declare
  exam uuid := (select id from certifications where slug = ${target});
begin
  if (select count(*) from cert_questions where certification_id = exam and is_active) <> ${after} then
    raise exception '${examCode}: expected ${after} active questions';
  end if;
  if exists (select 1 from cert_questions where certification_id = exam and is_active and sub_objective_id is null) then
    raise exception '${examCode}: a question has no topic';
  end if;
${topicCheck(target, counts, `${examCode}: a topic has the wrong number of questions`)}
${liveFixes
  .map(
    (f) => `  if not exists (
    select 1 from cert_questions
    where id = ${str(f.id)} and is_active
      and question_text = ${str(f.question ?? f.was.question)}
      and explanation = ${str(f.explanation)}${f.options ? `\n      and correct_index = ${f.answer}` : ""}
  ) then
    raise exception ${str(`${examCode}: live question ${f.id} was not corrected`)};
  end if;`
  )
  .join("\n")}
end $$;`);

  out.push(`commit;`, ``);
  return out.join("\n\n");
}
